import {
    Column,
    CreateDateColumn,
    Entity,
    Index,
    JoinColumn,
    ManyToOne,
    PrimaryGeneratedColumn,
    Unique,
    UpdateDateColumn,
} from 'typeorm';
import { User } from './User';

export enum EmailBroadcastStatus {
    QUEUED = 'queued',
    SENDING = 'sending',
    COMPLETED = 'completed',
    COMPLETED_WITH_ERRORS = 'completed_with_errors',
}

// One "send" by an admin: subject + rich content to up to 1 000 recipients. See specs/002-admin-send-email.
@Entity('email_broadcasts')
@Unique('UQ_email_broadcasts_client_request', ['created_by', 'client_request_id'])
@Index('IDX_email_broadcasts_tenant_created', ['tenant_id', 'created_at'])
export class EmailBroadcast {
    @PrimaryGeneratedColumn()
    id!: number;

    @Column({ type: 'int', nullable: true })
    created_by!: number | null;

    @Column({ type: 'int', nullable: true })
    tenant_id!: number | null;

    // Generated by the web form once per compose, so double clicks create a single broadcast.
    @Column({ type: 'uuid' })
    client_request_id!: string;

    @Column({ type: 'varchar', length: 200 })
    subject!: string;

    // Validated TipTap document as submitted
    @Column({ type: 'jsonb' })
    content_json!: Record<string, any>;

    // Rendered by the server from content_json (allow-listed tags only)
    @Column({ type: 'text' })
    content_html!: string;

    @Column({ type: 'text' })
    content_text!: string;

    @Column({ type: 'int' })
    recipient_count!: number;

    @Column({ type: 'int', default: 0 })
    sent_count!: number;

    @Column({ type: 'int', default: 0 })
    failed_count!: number;

    @Column({ type: 'varchar', length: 30, default: EmailBroadcastStatus.QUEUED })
    status!: string;

    @Column({ type: 'timestamptz', nullable: true })
    started_at!: Date | null;

    @Column({ type: 'timestamptz', nullable: true })
    completed_at!: Date | null;

    @CreateDateColumn({ type: 'timestamptz' })
    created_at!: Date;

    @UpdateDateColumn({ type: 'timestamptz' })
    updated_at!: Date;

    @ManyToOne(() => User, { onDelete: 'SET NULL' })
    @JoinColumn({ name: 'created_by', foreignKeyConstraintName: 'FK_email_broadcasts_created_by' })
    creator!: User | null;
}
